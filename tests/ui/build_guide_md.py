"""
Writes docs/GUIDE.md from the guide of the editor, as the editor shows it (tables filled with the
game data of source/app/data/gamedata.js).

    python tests/ui/serve.py <folder with quest1..quest5 and otomo1>      (in a first console)
    python tests/ui/build_guide_md.py [--chrome <path>]                    (in a second console)

Needs Python 3 with Playwright and Chrome or Chromium, like screenshots.py. The calculator and the
table of IDs of your own game are left out (they depend on what you type or on your save).
"""
import asyncio
import os
import sys

from playwright.async_api import async_playwright

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "docs", "GUIDE.md"))
BASE = "http://localhost:8765/index.html"
CHROME = sys.argv[sys.argv.index("--chrome") + 1] if "--chrome" in sys.argv else None
SECTIONS = [("stats", "How strong is a monster?"), ("monsters", "Monsters"), ("special", "The Special field"),
            ("ids", "Quest IDs"), ("maps", "Maps"), ("hidden", "Hidden parameters")]

# DOM -> markdown, run in the page on the section's container
TO_MD = r"""
(root) => {
  function inline(n) {
    if (n.nodeType === 3) return n.nodeValue.replace(/\s+/g, ' ');
    if (n.nodeType !== 1) return '';
    var t = n.tagName.toLowerCase(), s = '';
    if (skip(n)) return '';
    for (var c = n.firstChild; c; c = c.nextSibling) s += inline(c);
    if (t === 'b' || t === 'strong') return s.trim() ? '**' + s.trim() + '** ' : '';
    if (t === 'i' && !n.className) return s.trim() ? '*' + s.trim() + '* ' : '';
    if (t === 'code') return '`' + s.trim() + '`';
    if (t === 'br') return ' ';
    if (/\blabel\b/.test(n.className) && s.trim()) return ' *(' + s.trim() + ')* ';
    return s;
  }
  function skip(n) {
    var t = n.tagName.toLowerCase();
    if (t === 'input' || t === 'select' || t === 'button' || t === 'script' || t === 'style') return true;
    if (n.getAttribute('data-md') === 'skip') return true;
    if (/\b(form|button|buttons|menu)\b/.test(n.className)) return true;
    var cs = getComputedStyle(n);
    return cs.display === 'none' || cs.visibility === 'hidden';
  }
  function clean(s) { return s.replace(/\s+/g, ' ').replace(/\s+([,.;:)])/g, '$1').replace(/\*\* \*\*/g, ' ').trim(); }
  function cell(s) { return clean(s).replace(/\|/g, '\\|'); }
  var out = [];
  function block(n) {
    if (n.nodeType !== 1 || skip(n)) return;
    var t = n.tagName.toLowerCase();
    if (/^h[1-4]$/.test(t)) { out.push('#'.repeat(Math.max(2, parseInt(t[1], 10))) + ' ' + clean(inline(n))); return; }
    if (t === 'p') { var p = clean(inline(n)); if (p) out.push(p); return; }
    if (t === 'ul' || t === 'ol') {
      var items = [];
      for (var li = n.firstElementChild; li; li = li.nextElementSibling) { if (!skip(li)) { var x = clean(inline(li)); if (x) items.push('* ' + x); } }
      if (items.length) out.push(items.join('\n'));
      return;
    }
    if (t === 'table') {
      var rows = [], head = [];
      n.querySelectorAll('thead th').forEach(function (th) { if (!skip(th)) head.push(cell(inline(th))); });
      n.querySelectorAll('tbody tr').forEach(function (tr) {
        if (skip(tr)) return;
        var r = []; tr.querySelectorAll('td, th').forEach(function (td) { if (!skip(td)) r.push(cell(inline(td))); });
        if (r.join('')) rows.push(r);
      });
      if (!rows.length) return;
      var w = Math.max(head.length, Math.max.apply(null, rows.map(function (r) { return r.length; })));
      while (head.length < w) head.push('');
      var md = ['| ' + head.join(' | ') + ' |', '|' + head.map(function () { return '---'; }).join('|') + '|'];
      rows.forEach(function (r) { while (r.length < w) r.push(''); md.push('| ' + r.join(' | ') + ' |'); });
      out.push(md.join('\n'));
      return;
    }
    for (var c = n.firstElementChild; c; c = c.nextElementSibling) block(c);
  }
  block(root);
  return out.join('\n\n');
}
"""


async def main():
    async with async_playwright() as p:
        opts = {"args": ["--no-sandbox"]}
        if CHROME:
            opts["executable_path"] = CHROME
        browser = await p.chromium.launch(**opts)
        page = await browser.new_page(viewport={"width": 1320, "height": 900})
        with open(os.path.join(HERE, "pako.min.js"), encoding="utf-8") as f:
            await page.add_init_script(f.read())
        with open(os.path.join(HERE, "shim.js"), encoding="utf-8") as f:
            await page.add_init_script(f.read())
        parts = ["# Guide", "",
                 "*The built-in guide of the editor (Guide button of the library), as text. Generated by "
                 "`tests/ui/build_guide_md.py`: the interactive calculator and the table of the IDs of "
                 "your own game are only in the editor.*"]
        for sec, _title in SECTIONS:
            await page.goto(BASE + "#/guide/" + sec)
            await page.wait_for_timeout(2500)
            root = await page.query_selector("[ng-if=\"section === '%s'\"]" % sec)
            md = await page.evaluate(TO_MD, root)
            parts += ["", md]
        await browser.close()
    text = "\n".join(parts).rstrip() + "\n"
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("written", OUT, len(text), "characters")


asyncio.run(main())
